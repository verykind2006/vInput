import Foundation

/// 翻译一段文本要给多少时间、多少 token。**两个数都随长度走。**
///
/// # 为什么不能是常数
///
/// 原来超时固定 8 秒、`maxTokens` 固定 512，两个数都是拿基准集定的——
/// 而基准集 26 条的中文字数是 **15–64、中位 37**。实际使用里一段口述常有
/// 一两百字，之前还出过三分钟长语音的 bug。
///
/// 2026-08-19 分档实测（`qwen3-4b-instruct-2507-4bit`，中译英，
/// `Bench/translate-longform.json`）：
///
/// | 中文字数 | 耗时 |
/// |---|---|
/// | 35 | 1.3 秒 |
/// | 48 | 1.3 秒 |
/// | 82 | 2.7 秒 |
/// | 101 | 3.3 秒 |
/// | 154 | 5.4 秒 |
/// | 191 | **7.1 秒** |
/// | 315 | **11.1 秒** |
/// | 589 | **24.7 秒** |
///
/// 约 **0.042 秒/字**，**断点在 190 字左右**——超过就撞穿 8 秒预算、
/// 退回中文原文，而用户看到的只是「翻译时灵时不灵」。
///
/// # token 上限那一半是保险，不是在修一个已发生的问题
///
/// 589 字的译文有 2459 个字符，按此前实测的 4.4–5.2 字符每 token 换算是
/// 470–560 token，**看着贴着 512 的上限**。但放大 `maxTokens` 之后原样复跑，
/// 八条译文**逐字未变**（长度与残留汉字数全部相同）——说明那一条是自然
/// 收尾的，不是被截断的，实际的 token 密度高于估算区间的下沿。
///
/// **所以这一半是给更长输入留的余量，不是在修一个当时正在发生的截断。**
/// 留着它的理由仍然成立：撞上限的表现是**静默返回半截译文**，而半截译文
/// 往往是完全合法的目标语言文本，事后与超时半途而废分不开
/// （见 `TruncationSignal`）。
enum TranslationBudget {
    /// 每个字给多少秒。
    ///
    /// 实测斜率 0.042，取 0.05 是留约 19% 余量：那批数据只跑了一个模型、
    /// 一种目标语言，而西语德语实测比英语慢（M8 第 0 步：单句最长
    /// 英 2.9 / 西 4.3 / 德 4.9 秒）。
    static let secondsPerCharacter = 0.05

    /// 下限。短句仍然按老规矩走，不因为这次改动而变。
    ///
    /// 8 秒的由来：4B 在单句上实测最长 4.9 秒（德语），约 1.6 倍余量。
    static let floor: Duration = .seconds(8)

    /// 云端后端的下限。**本机那个 8 秒在云端上是错的。**
    ///
    /// 2026-08-19 真实联网实测（`gemini-3.6-flash`，一句 20 字的中文）：
    /// 8 次成功 7 次，**均 7.2 秒、最长 12.7 秒**。而 20 字按 0.05 算只有
    /// 1 秒，会落到 8 秒的下限上——**于是即使云端成功返回，我们也会在 8 秒
    /// 把它掐掉、退回中文原文**，用户看到的是「云端翻译好像根本没生效」。
    ///
    /// 25 秒 = 实测最长 12.7 秒的约两倍。没取更大是因为超时同时也是
    /// 「最坏情况下用户干等多久」——云端不占本机的模型容器，但占用户的耐心。
    ///
    /// ⚠️ **这个数是中国 + VPN 下量出来的，不是 Gemini 的真实表现。**
    /// 用户 2026-09-01 到西班牙，那时要重测，多半可以大幅调低。
    /// 同一轮里 `gemini-3.5-flash` 出现过一次 88.2 秒——那种量级不该迁就，
    /// 迁就它等于让用户为一次异常干等一分半。
    static let cloudFloor: Duration = .seconds(25)

    /// 上限。**不设的话，一段异常长的文本会把模型容器占死几分钟。**
    ///
    /// `ModelContainer.perform` 是串行的，而超时**不会真的停下推理**
    /// （取消传不进 MLX 生产方，GPU 照跑到 EOS——`MLXTranslator` 里记着
    /// 那次 8/8 的 probe 实测）。所以超时预算同时也是「最坏情况下后面那句话
    /// 要等多久」。
    ///
    /// 30 秒的由来：听写会话本身有 90 秒上限（`MouseVoiceSession.Limit
    /// .dictation`，那个数有实测支撑），按中文口语约 4–5 字/秒换算，
    /// 一次口述最多约 450 字，×0.05 = 22.5 秒。30 秒在此之上留余量。
    ///
    /// **撞到上限意味着这次多半会退回中文原文**——那是有意的：
    /// 等超过半分钟才拿到译文，不如早点把中文给用户。
    static let ceiling: Duration = .seconds(30)

    /// 这段文本按长度算出来的预算，**只夹上限，不夹下限**。
    ///
    /// 下限由调用方给（`TranslationPipeline` 用它的 `timeout` 参数）。
    /// 在这里也夹一次下限的话，构造参数就变成「只能抬不能降」——
    /// 显式传一个小超时会被无声无息地忽略掉，而那正是测试用来验证超时路径的
    /// 手段。**一个参数不按它字面的意思生效，是最难查的一类问题。**
    static func scaled(forCharacters count: Int) -> Duration {
        min(Duration.seconds(Double(count) * secondsPerCharacter), ceiling)
    }

    /// 每个中文字大约要产出多少 token。
    ///
    /// 实测反推：589 字的输入产出约 470–560 token ⇒ 约 0.8–0.95 token/字。
    /// 取 2 是**刻意给足两倍余量**——`maxTokens` 限的是单次推理长度，
    /// 限不住耗时（真正的时间闸门在 `timeout` 那一侧），所以给大的代价很小，
    /// 而给小的代价是**静默返回半截译文**，事后与超时半途而废分不开。
    static let tokensPerCharacter = 2

    /// 下限。短句照旧 512，与改动前一致。
    static let minimumTokens = 512

    /// 这段文本给多少 token 上限。
    static func maxTokens(forCharacters count: Int) -> Int {
        max(minimumTokens, count * tokensPerCharacter)
    }
}

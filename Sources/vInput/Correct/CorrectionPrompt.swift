import Foundation

/// 给校正模型的指令。
///
/// 提示词只是第一层约束，真正的保障是拼音闸门——提示词写得再好，
/// 4B 模型也会时不时自作主张。
///
/// **这一版是照着真机日志改的。** 用户跑了 7 次、采纳数为 0，失败全都不是
/// 「常识不够」，而是「没听懂任务」：把本来正确的「小米」改成「米粒」、
/// 把「情况」换成同义的「状况」、输出「长句子→长句子」这种空操作、
/// 对不认识的「矩子」顺着字形猜成「矩形」。据此加了四道约束：
///
/// 1. **说清基准率**——「无」是最常见的正确回答。这一条是止住乱改的主力：
///    实测把「小米→米粒」「情况→状况」直接变成了「无」。
/// 2. **只顺读音、别顺字形**——针对「矩子→矩形」那类联想。
/// 3. **规定箭头方向**——左边是不成词的字，右边是常用词。少了这条，模型
///    会拿示例反着套：实测出现过把正确的「小米遥控器」改成「小米耀空气」，
///    而它同音、闸门拦不住，是真会写进用户文档的事故。
/// 4. **禁止空操作**（箭头两边必须不同）。
/// 5. **英文照抄，连大小写都不许动**——这条是补出来的：只写「英文原样保留」
///    时，模型把本来正确的 `useEffect` 改成了 `useeffect`。**闸门的读音比对
///    拦不住它**，`Pinyin.toneless` 会先转小写，大小写差异在闸门眼里根本
///    不存在。把「useEffect 就该一直是 useEffect」写进规则后不再复现。
///
///    单个英文词还有长度规则兜着（拉丁词只有 1 段，够不着
///    `CorrectionGate.minimumOriginalLength`），但 Whisper 常把标识符拆开写
///    （`Use Effect`），那种原文有 2 段、长度规则不再兜底；而闸门为了放行
///    「拼回去」已经把拉丁段里的空格一并归一化了（见
///    `CorrectionGate.joiningLatinWords`），大小写与空格这一层就**只剩这条
///    提示词**。它不是可有可无的措辞，是那一格唯一的防线。
///
/// 每一条都在真机语料上验证过：加基准率那条之后，「小米→米粒」「情况→状况」
/// 「长句子→长句子」三类建议一次都没再出现过。
///
/// 示例刻意只用真机语料，且**不放编造的例子**：试过加一条自造的
/// 「代马→代码」来示范「按读音联想」，模型转头就把「代马→代码」原样输出到
/// 一句压根没有「代马」的话上——编的例子会被当成答案背下来。
enum CorrectionPrompt {
    /// 没有发现错误时约定的输出。刻意选一个不含箭头的词，
    /// 于是它天然被解析成空清单，不需要额外的特判分支。
    static let noChangeMarker = "无"

    static let instructions = """
        语音识别只听得见读音，落成文字时会挑错同音的字。你的唯一工作：把挑错的字换回读音相同的正确写法。

        大多数句子本来就是对的，「\(noChangeMarker)」是最常见的正确回答。只有当某几个字连起来根本不成词、在句子里讲不通时，才去想它读音相同的正确写法是什么。

        错字是听出来的，不是看出来的：错字和正确写法读音相同，字形往往毫不相干。所以只顺着读音去想，别顺着字形联想（看到一个字就想它常出现在哪个词里，那是字形联想，会想歪）。

        句子里的英文单词、代码标识符、数字，一律照抄不动：不许改大小写（比如 useEffect 就该一直是 useEffect）、不许加空格删空格、不许拆开或合并。它们不是同音错字，语音识别没听错它们。

        输出替换清单，一行一条，格式：原文→正确文本
        箭头左边必须是那几个不成词的字，右边必须是读音相同的常用词。方向不能反。
        取最短的那一段：只把不成词的那几个字放在箭头左边，前后本来就正确的字不要包进来。
        没有要改的，就只输出一个字：\(noChangeMarker)
        不要编号、引号、理由、推理过程——只有清单或者「\(noChangeMarker)」。

        写下一条替换之前，先自问三句，有一句答不上就不写：
        1. 原文那几个字真的讲不通吗？——是正常的词、品牌名、人名、地名、英文、代码标识符，就讲得通，不许动。
        2. 换过去以后读音一模一样吗？——只允许声调不同。拼音不一样的行会被系统自动丢弃，写了也没用。
        3. 箭头两边不一样吧？——一模一样的行没有意义，不要写。

        禁止：换意思相近但读音不同的词、改语序、改标点、把英文翻成中文。
        下面示例里的词只是示范，不要把它们套到新句子上。
        拿不准就输出 \(noChangeMarker)。漏掉一个错字没关系，改错一个本来对的词才是事故。

        示例一
        输入：小米耀空气很好用
        回答：
        耀空气→遥控器

        示例二
        输入：好的 我又跑了一遍你检查一下日志看看具体是什么情况
        回答：
        \(noChangeMarker)

        示例三
        输入：对于这种中英文夹杂比如我们说Claude Code Open AI LLM这种识别度如何
        回答：
        \(noChangeMarker)
        """

    /// 完整的用户提示：规则 + 待校正文本。
    ///
    /// **规则必须并进用户消息，不能走 `ChatSession(instructions:)`。**
    /// mlx-swift-examples 2.29.1 的 `respond(to:)` 与 `streamResponse(to:)`
    /// 都是 `generator.messages = [.user(...)]`——赋值而非追加，把 init 里
    /// 设进去的系统消息整个冲掉（`Streamlined.swift:43` vs `:196/:237`）。
    /// 结果是 `instructions:` 静默失效。
    ///
    /// 真机实测过后果：模型收到的只有「输入：…\n回答：」，于是开始聊天——
    /// 「小米耀空气可能是指小米推出的某款智能设备……」，一条替换都没有。
    /// 这个缺陷不会以任何错误的形式暴露，只表现为「校正好像没用」。
    static func user(for text: String) -> String {
        """
        \(instructions)

        输入：\(text)
        回答：
        """
    }
}
